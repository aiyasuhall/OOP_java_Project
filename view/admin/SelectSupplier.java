    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (jTable1.getSelectedRow() >= 0) {
            rowIndex = jTable1.getSelectedRow();
            int id = Integer.parseInt(model.getValueAt(rowIndex, 0).toString());
            String supp = jComboBox1.getSelectedItem().toString();
            String status = "On the way";
            boolean success = purchaseController.setSuppStatus(id, supp, status);
            if (success) {
                JOptionPane.showMessageDialog(this, "Supplier assigned and status updated!");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update supplier/status.", "Error", JOptionPane.ERROR_MESSAGE);
            }
            jTable1.setModel(new DefaultTableModel(null, new Object[]{"Purchase ID", "User ID", "Username", "Phone", "Product ID", "Product Name", "Quantity", "Price", "Total", "Purchased Date", "Address", "Received Date", "Supplier Name", "Status"}));
            purchaseController.getProductsValue(jTable1, "");
        } else {
            JOptionPane.showMessageDialog(this, "No product has been selected", "Warning", 2);
        }
}//GEN-LAST:event_jButton2ActionPerformed

